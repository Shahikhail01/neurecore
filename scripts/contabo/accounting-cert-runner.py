BACKEND = "http://127.0.0.1:3003"

def run(cmd: str) -> str:
    return subprocess.check_output(
        cmd, shell=True, executable="/bin/bash",
        stderr=subprocess.STDOUT, text=True,
    ).strip()

def psql(sql: str) -> str:
    """Run psql as the postgres user (peer auth, no password needed).

    Uses tempfile.mkstemp for atomic creation in /tmp. The mkstemp
    file is created with mode 0600 owned by root, which the postgres
    user cannot read; we chmod to 0644 so sudo -u postgres can read
    (sandboxed because the SQL is generated by this script).
    The pid-based suffix prevents collisions across concurrent runs.
    """
    fd, fpath = tempfile.mkstemp(prefix="cert-psql-", suffix=".sql", dir="/tmp")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(sql + "\n")
        os.chmod(fpath, 0o644)
        return run(f"sudo -u postgres psql -h 127.0.0.1 -U postgres -d neurecore_prod -tA -f {fpath}")
    finally:
        try: os.unlink(fpath)
        except OSError: pass

def api(method, path, token=None, body=None) -> tuple[int, Any]:
    headers = {"Content-Type": "application/json"}
    if token: headers["Authorization"] = f"Bearer {token}"
    data = json.dumps(body).encode() if body else None
    req = urllib.request.Request(f"{BACKEND}{path}", method=method, headers=headers, data=data)
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            text = r.read().decode()
            try: return r.status, json.loads(text)
            except: return r.status, text
    except urllib.error.HTTPError as e:
        text = e.read().decode()
        try: return e.code, json.loads(text)
        except: return e.code, text

def banner(label: str, ok: bool, detail: str = "") -> bool:
    sym = "✅" if ok else "❌"
    print(f"{sym}  {label}{(': ' + detail) if detail else ''}")
    return ok

def mint_jwt(user_id: str, role: str, tenant_id: str | None) -> str:
    secret = run("grep ^JWT_SECRET= /opt/neurecore/backend/backend/.env.production | head -1 | cut -d= -f2-")
    header = {"alg": "HS256", "typ": "JWT"}
    payload = {
        "sub": user_id,
        "email": f"{role.lower()}@test.com",
        "role": role,
        "tenantId": tenant_id,
        "sessionId": f"cert-{secrets.token_hex(8)}",
        "exp": int(time.time()) + 3600,
        "iss": "neurecore",
        "aud": "neurecore-api",
    }
    def _b64(d):
        import base64, json as _j
        return base64.urlsafe_b64encode(_j.dumps(d, separators=(",", ":")).encode()).rstrip(b"=").decode()
    h_b64 = _b64(header); p_b64 = _b64(payload)
    sig = __import__("hmac").new(secret.encode(), (h_b64 + "." + p_b64).encode(), __import__("hashlib").sha256).digest()
    sig_b64 = __import__("base64").urlsafe_b64encode(sig).rstrip(b"=").decode()
    return f"{h_b64}.{p_b64}.{sig_b64}"

